/**
 * dsh-engineering-skills — host half.
 *
 * Matt Pocock's engineering + productivity agent skills (grilling, spec/ticket
 * flows, TDD, code review, domain modelling, handoff, …), vendored from
 * https://github.com/mattpocock/skills and registered as ONE bundled skill
 * provider — the same shape the shipped `@deepseek-ai/dsh-skill-office` uses.
 *
 * Why a provider rather than plain files: a provider keeps the skills owned by
 * this package (`dsh plugin add` / `remove` is the whole lifecycle), lets the
 * upstream invocation split survive into this harness's policy model, and
 * leaves the user's `~/.agents/skills` and workspace `.dsh/skills` untouched.
 *
 * Invocation mapping (upstream → DeepSeek Harness):
 *   disable-model-invocation: true  → { modelInvocable: false, userInvocable: true }
 *   default                         → { modelInvocable: true,  userInvocable: true }
 * A user-invoked skill is reachable only by typing `/<name>` in the composer
 * (the `/` menu lists it); a model-invoked one also enters the session catalog
 * and is loadable with the `skill` tool.
 */
import { readFileSync } from 'node:fs'
import { readFile } from 'node:fs/promises'
import { join, sep } from 'node:path'
import { fileURLToPath } from 'node:url'
import z from '@deepseek-ai/schemastery'
import { BUNDLED_SKILL_RANK } from '@deepseek-ai/dsh-skill'

/** Cordis plugin identity (the profile row id is chosen by cordis.patch.yml). */
export const name = 'engineering-skills'

/** The skill registry is a hard dependency: a bare ctx.get() races the composition. */
export const inject = ['skills']

const SKILLS_ROOT = fileURLToPath(new URL('../skills/', import.meta.url))
const MANIFEST_PATH = join(SKILLS_ROOT, 'manifest.json')

const CATEGORIES = ['engineering', 'productivity']

/**
 * Appended to every loaded skill body unless `appendHarnessGuide: false`.
 * Upstream prose is written harness-neutral but occasionally says "sub-agent"
 * or "background agent"; this maps those words onto this harness's tools.
 * Kept short — it is paid on every loaded skill.
 */
const HARNESS_GUIDE = `## DeepSeek Harness notes
This skill is vendored from Matt Pocock's skills. Where it says "sub-agents"/"subagents", use this harness's \`subagent\` tool (or \`workflow\` for many parallel agents; \`subagent_fork\` when the child should inherit this conversation). Where it says "background agent", use a \`subagent\` and collect it later. \`skill\` loads skills, \`todo_write\` tracks tasks, \`ask_user_question\` asks structured questions. Workspace instruction files are \`AGENTS.md\` / \`CLAUDE.md\`; both are read.`

export const Config = z.object({
  /** Provider name in the skill registry; change only to dodge a collision. */
  providerName: z.string().min(1).default('engineering-skills'),
  /** Which upstream buckets to expose. Fewer skills means a smaller catalog prompt. */
  categories: z.array(z.union([z.const('engineering'), z.const('productivity')])).default([...CATEGORIES]),
  /** Explicit skill-name subset; empty means "every selected category". */
  skills: z.array(z.string()).default([]),
  /** Set false to load upstream bodies verbatim. */
  appendHarnessGuide: z.boolean().default(true),
})

/** Read `skills/manifest.json` (generated by scripts/sync-upstream.mjs). */
export function readManifest() {
  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'))
  if (manifest.schemaVersion !== 1) throw new Error(`engineering-skills: unsupported manifest schema ${manifest.schemaVersion}`)
  if (!Array.isArray(manifest.skills) || manifest.skills.length === 0) throw new Error('engineering-skills: manifest lists no skills')
  return manifest
}

/**
 * Apply the configured category + name selection. Throws on an unknown name:
 * a typo silently shrinking the catalog is worse than a failed mount.
 */
export function selectSkills(manifest, { categories = CATEGORIES, skills = [] } = {}) {
  const unknownCategories = categories.filter((category) => !CATEGORIES.includes(category))
  if (unknownCategories.length > 0) {
    throw new Error(`engineering-skills: unknown categor${unknownCategories.length > 1 ? 'ies' : 'y'} ${unknownCategories.map((c) => `"${c}"`).join(', ')} (expected ${CATEGORIES.join(', ')})`)
  }
  const known = new Set(manifest.skills.map((skill) => skill.name))
  const unknownSkills = skills.filter((skillName) => !known.has(skillName))
  if (unknownSkills.length > 0) {
    throw new Error(`engineering-skills: unknown skill${unknownSkills.length > 1 ? 's' : ''} ${unknownSkills.map((s) => `"${s}"`).join(', ')} (available: ${[...known].sort().join(', ')})`)
  }
  return manifest.skills.filter((skill) => categories.includes(skill.category) && (skills.length === 0 || skills.includes(skill.name)))
}

/** Strip YAML frontmatter — the registry renders the body, not the metadata block. */
function bodyOf(raw, where) {
  const match = /^---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/u.exec(raw)
  if (match === null) throw new Error(`engineering-skills: ${where} has no YAML frontmatter`)
  return raw.slice(match[0].length).trim()
}

/** Build the registry candidates the provider will advertise. */
function candidatesFor(selected, providerName) {
  return selected.map((skill) => {
    const directory = join(SKILLS_ROOT, ...skill.dir.split('/'))
    return {
      name: skill.name,
      description: skill.description,
      invocation: {
        modelInvocable: skill.modelInvocable,
        userInvocable: skill.userInvocable,
      },
      provider: providerName,
      source: 'bundled',
      rank: BUNDLED_SKILL_RANK,
      resourceBase: {
        kind: 'directory',
        path: directory.split(sep).join('/'),
      },
      locator: join(directory, 'SKILL.md'),
      path: join(directory, 'SKILL.md'),
    }
  })
}

/**
 * Register the vendored skills with the skill registry.
 * @param ctx - context carrying the injected `skills` service.
 * @param config - validated `Config` value (defaults applied by cordis; the
 *   fallbacks here keep a bare `apply(ctx)` call working in tests).
 */
export function apply(ctx, config = {}) {
  const resolved = {
    providerName: config.providerName ?? 'engineering-skills',
    categories: config.categories ?? [...CATEGORIES],
    skills: config.skills ?? [],
    appendHarnessGuide: config.appendHarnessGuide ?? true,
  }
  const manifest = readManifest()
  const selected = selectSkills(manifest, resolved)
  const candidates = candidatesFor(selected, resolved.providerName)

  /** @type {import('@deepseek-ai/dsh-skill').SkillProvider} */
  const provider = {
    name: resolved.providerName,
    list: () => Promise.resolve(candidates),
    async get(candidate, options) {
      const raw = await readFile(candidate.locator, { encoding: 'utf8', signal: options?.signal })
      const content = bodyOf(raw, candidate.name) + (resolved.appendHarnessGuide ? `\n\n${HARNESS_GUIDE}` : '')
      const { rank: _rank, locator: _locator, ...summary } = candidate
      return { ...summary, content }
    },
  }
  ctx.skills.registerProvider(() => provider)
}
